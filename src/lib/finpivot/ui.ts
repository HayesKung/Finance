export function t(locale: Locale, key: UiKey): string {
  return locale === "en" ? en[key] : zh[key];
}

export function footerLine(locale: Locale): string {
  return locale === "en"
    ? `${META.owner} tracks · ${META.reviewer} checks · ${META.checkpoint}`
    : `${META.owner} 跟踪 · ${META.reviewer} 核验 · ${META.checkpoint}`;
}

export function askedLine(locale: Locale, done: number, total: number): string {
  return locale === "en" ? `Asked ${done} / ${total}` : `已问 ${done} / ${total}`;
}

export function leadCount(locale: Locale, n: number): string {
  return locale === "en" ? `${n} on the list` : `当前 ${n} 家`;
}

